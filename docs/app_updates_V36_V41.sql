-- Existing profile years are explicit historical membership evidence. Their
-- actual calendar dates are unknown; do not invent dates or activate a session.
INSERT INTO app.academic_sessions(name,description)
SELECT DISTINCT p.academic_year,'Historical session imported from existing profile academic year; calendar dates were not recorded.'
FROM app.student_profiles p JOIN app.users u ON u.id=p.user_id WHERE u.role='STUDENT';
UPDATE app.users SET academic_session_id=(SELECT s.id FROM app.academic_sessions s JOIN app.student_profiles p ON p.academic_year=s.name WHERE p.user_id=app.users.id)
WHERE role='STUDENT' AND EXISTS(SELECT 1 FROM app.student_profiles p WHERE p.user_id=app.users.id);

