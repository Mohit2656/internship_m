package edu.institution.ims.dashboard.report;

import org.apache.pdfbox.pdmodel.*;
import org.apache.pdfbox.rendering.PDFRenderer;
import org.apache.pdfbox.text.*;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;
import javax.imageio.ImageIO;
import java.io.IOException;
import java.nio.file.*;
import java.time.ZoneId;
import java.util.*;
import java.util.stream.*;
import static org.assertj.core.api.Assertions.*;

class DashboardReportPdfWriterTest {
    @TempDir Path temporary;
    private static DashboardReportCatalog.Field field(String id, String label) {
        return new DashboardReportCatalog.Field(id,label,"Report",DashboardReportCatalog.Kind.TEXT,true,null,false);
    }

    @Test void shortPdfPreservesSelectedDataMetadataStandardFontsAndPageNumbers() throws Exception {
        Path file=temporary.resolve("short.pdf");
        try(var writer=new DashboardReportWriter(file,DashboardReportRequest.Format.PDF,
                List.of(field("name","Student"),field("company","Company"),field("period","Reporting period")),ZoneId.of("Asia/Kolkata"))) {
            writer.row(Map.of("name","José Student","company","Example Ltd","period","01 Sep - 30 Sep 2026"));
            writer.finish(Map.of("Generated by","mentor@example.edu","Access scope","Assigned students"));
            assertThat(writer.count()).isEqualTo(1);
        }
        try(PDDocument pdf=PDDocument.load(file.toFile())) {
            assertThat(pdf.getNumberOfPages()).isEqualTo(1);
            assertThat(new PDFTextStripper().getText(pdf)).contains("José Student","Example Ltd","01 Sep - 30 Sep 2026","mentor@example.edu","Page 1 of 1");
            assertStandardFontsAndBounds(pdf);
            renderReview(pdf,"short",0);
        }
    }

    @Test void narrowPdfSplitsLongRowsAndRepeatsHeadersWithoutClippingOrLosingLastLines() throws Exception {
        Path file=temporary.resolve("long-table.pdf");
        String body=IntStream.range(0,220).mapToObj(n->"Progress line " + n + ": implemented and verified the internship report.").collect(Collectors.joining("\n"));
        body+="\n"+"W".repeat(220)+"\nNARROW-END";
        try(var writer=new DashboardReportWriter(file,DashboardReportRequest.Format.PDF,
                List.of(field("uid","Student UID"),field("work","Work description")),ZoneId.of("Asia/Kolkata"))) {
            writer.row(Map.of("uid","00001","work",body));
            writer.row(Map.of("uid","00002","work","SECOND-STUDENT-END"));
            writer.finish(Map.of("Record count","2"));
        }
        try(PDDocument pdf=PDDocument.load(file.toFile())) {
            assertThat(pdf.getNumberOfPages()).isGreaterThan(5);
            String text=new PDFTextStripper().getText(pdf);
            assertThat(text).contains("Progress line 0:","Progress line 219:","NARROW-END","SECOND-STUDENT-END","Page "+pdf.getNumberOfPages()+" of "+pdf.getNumberOfPages());
            assertStandardFontsAndBounds(pdf);
            PDFTextStripper firstPage=new PDFTextStripper(); firstPage.setStartPage(2);firstPage.setEndPage(2);
            assertThat(firstPage.getText(pdf)).contains("Student UID","Work description");
            renderReview(pdf,"long-table-first",0);
            renderReview(pdf,"long-table-middle",pdf.getNumberOfPages()/2);
            renderReview(pdf,"long-table-last",pdf.getNumberOfPages()-1);
        }
    }

    @Test void widePdfKeepsAllColumnsAsReadableSectionsAcrossPages() throws Exception {
        Path file=temporary.resolve("wide.pdf");
        List<DashboardReportCatalog.Field> fields=IntStream.range(0,9).mapToObj(n->field("field"+n,"Selected column "+n)).toList();
        Map<String,Object> row=new LinkedHashMap<>();
        for(int n=0;n<9;n++) row.put("field"+n,"VALUE-"+n);
        row.put("field4",IntStream.range(0,100).mapToObj(n->"Wide report narrative line "+n+" with the actual submitted work content.").collect(Collectors.joining("\n"))+"\nWIDE-END");
        try(var writer=new DashboardReportWriter(file,DashboardReportRequest.Format.PDF,fields,ZoneId.of("Asia/Kolkata"),"Monthly Progress Reports","Attedance report ")) {
            writer.row(row);writer.finish(Map.of("Approval status","PENDING_MENTOR_REVIEW"));
        }
        try(PDDocument pdf=PDDocument.load(file.toFile())) {
            assertThat(pdf.getNumberOfPages()).isGreaterThan(2);
            String text=new PDFTextStripper().getText(pdf);
            for(int n=0;n<9;n++) {
                assertThat(text).contains("Selected column "+n);
                if(n!=4) assertThat(text).contains("VALUE-"+n);
            }
            assertThat(text).contains("WIDE-END","PENDING_MENTOR_REVIEW","Record 1","Report details");
            assertStandardFontsAndBounds(pdf);
            renderReview(pdf,"wide-first",0);
            renderReview(pdf,"wide-last",pdf.getNumberOfPages()-1);
        }
    }

    @Test void emptyPdfStatesNoResultsAndStillIncludesSelectedColumnLabels() throws Exception {
        Path file=temporary.resolve("empty.pdf");
        try(var writer=new DashboardReportWriter(file,DashboardReportRequest.Format.PDF,List.of(field("uid","Student UID")),ZoneId.of("Asia/Kolkata"))) {
            writer.finish(Map.of("Record count","0"));
        }
        try(PDDocument pdf=PDDocument.load(file.toFile())) {
            assertThat(new PDFTextStripper().getText(pdf)).contains("Student UID","No records match the selected filters.","0 records","Page 1 of 1");
        }
    }

    @Test void unsupportedGlyphsFailExplicitlyAndDeleteIncompleteFiles() throws Exception {
        Path file=temporary.resolve("unsupported.pdf");
        assertThatThrownBy(()->{
            try(var writer=new DashboardReportWriter(file,DashboardReportRequest.Format.PDF,List.of(field("name","Student")),ZoneId.of("Asia/Kolkata"))) {
                writer.row(Map.of("name","Student \uD83D\uDE00"));writer.finish(Map.of());
            }
        }).isInstanceOf(IOException.class).hasMessageContaining("report PDF font cannot render");
        assertThat(Files.exists(file)).isFalse();
    }

    private static void assertStandardFontsAndBounds(PDDocument pdf) throws IOException {
        for(PDPage page:pdf.getPages()) {
            for(var name:page.getResources().getFontNames()) {
                var font=page.getResources().getFont(name);
                assertThat(font.getName()).isIn("Times-Roman", "Times-Bold");
                assertThat(font.isEmbedded()).isFalse();
            }
        }
        PDFTextStripper bounds=new PDFTextStripper() {
            @Override protected void processTextPosition(TextPosition position) {
                assertThat(position.getXDirAdj()).isGreaterThanOrEqualTo(47.5f);
                assertThat(position.getXDirAdj()+position.getWidthDirAdj()).isLessThanOrEqualTo(548f);
                assertThat(position.getYDirAdj()).isBetween(47f,809f);
                super.processTextPosition(position);
            }
        };
        bounds.getText(pdf);
    }

    private static void renderReview(PDDocument pdf,String name,int page) throws IOException {
        String configured=System.getProperty("report.pdf.preview-directory");
        if(configured==null||configured.isBlank()) return;
        Path directory=Path.of(configured);Files.createDirectories(directory);
        ImageIO.write(new PDFRenderer(pdf).renderImageWithDPI(page,110),"PNG",directory.resolve(name+".png").toFile());
    }
}
