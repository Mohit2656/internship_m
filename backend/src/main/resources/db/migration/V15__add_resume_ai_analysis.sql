CREATE TABLE resume_analyses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    resume_id BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL,
    model_name VARCHAR(200),
    model_version VARCHAR(200),
    started_at TIMESTAMP(6) WITH TIME ZONE,
    completed_at TIMESTAMP(6) WITH TIME ZONE,
    failure_reason_safe VARCHAR(100),
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_resume_analyses PRIMARY KEY (id),
    CONSTRAINT uk_resume_analyses_resume UNIQUE (resume_id),
    CONSTRAINT fk_resume_analyses_resume FOREIGN KEY (resume_id) REFERENCES student_resumes (id) ON DELETE CASCADE,
    CONSTRAINT chk_resume_analyses_status CHECK (status IN ('PENDING', 'PARSED', 'FAILED'))
);

CREATE TABLE resume_extracted_skills (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    analysis_id BIGINT NOT NULL,
    name VARCHAR(200) NOT NULL,
    sort_order INTEGER NOT NULL,
    CONSTRAINT pk_resume_extracted_skills PRIMARY KEY (id),
    CONSTRAINT fk_resume_extracted_skills_analysis FOREIGN KEY (analysis_id) REFERENCES resume_analyses (id) ON DELETE CASCADE,
    CONSTRAINT uk_resume_extracted_skills_name UNIQUE (analysis_id, name)
);

CREATE TABLE resume_extracted_experiences (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    analysis_id BIGINT NOT NULL,
    title VARCHAR(300),
    company VARCHAR(300),
    start_date VARCHAR(100),
    end_date VARCHAR(100),
    sort_order INTEGER NOT NULL,
    CONSTRAINT pk_resume_extracted_experiences PRIMARY KEY (id),
    CONSTRAINT fk_resume_extracted_experiences_analysis FOREIGN KEY (analysis_id) REFERENCES resume_analyses (id) ON DELETE CASCADE
);

CREATE TABLE resume_extracted_education (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    analysis_id BIGINT NOT NULL,
    degree VARCHAR(300),
    field VARCHAR(300),
    institution VARCHAR(400),
    sort_order INTEGER NOT NULL,
    CONSTRAINT pk_resume_extracted_education PRIMARY KEY (id),
    CONSTRAINT fk_resume_extracted_education_analysis FOREIGN KEY (analysis_id) REFERENCES resume_analyses (id) ON DELETE CASCADE
);

CREATE TABLE resume_extracted_certifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    analysis_id BIGINT NOT NULL,
    name VARCHAR(400) NOT NULL,
    sort_order INTEGER NOT NULL,
    CONSTRAINT pk_resume_extracted_certifications PRIMARY KEY (id),
    CONSTRAINT fk_resume_extracted_certifications_analysis FOREIGN KEY (analysis_id) REFERENCES resume_analyses (id) ON DELETE CASCADE,
    CONSTRAINT uk_resume_extracted_certifications_name UNIQUE (analysis_id, name)
);

CREATE INDEX idx_resume_analyses_status ON resume_analyses (status);
CREATE INDEX idx_resume_extracted_experiences_analysis ON resume_extracted_experiences (analysis_id);
CREATE INDEX idx_resume_extracted_education_analysis ON resume_extracted_education (analysis_id);
