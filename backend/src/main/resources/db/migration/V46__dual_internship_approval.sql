CREATE TABLE second_internship_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_user_id BIGINT NOT NULL REFERENCES users(id),
    existing_internship_id BIGINT NOT NULL REFERENCES internship_details(id),
    status VARCHAR(20) NOT NULL,
    pending_student_id BIGINT,
    approved_student_id BIGINT,
    requested_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    reviewed_by BIGINT REFERENCES users(id),
    reviewed_at TIMESTAMP(6) WITH TIME ZONE,
    rejection_reason VARCHAR(1000),
    CONSTRAINT uk_second_internship_pending UNIQUE (pending_student_id),
    CONSTRAINT uk_second_internship_approved UNIQUE (approved_student_id),
    CONSTRAINT ck_second_internship_status CHECK (status IN ('PENDING','APPROVED','REJECTED')),
    CONSTRAINT ck_second_internship_state CHECK (
      (status='PENDING' AND pending_student_id=student_user_id AND approved_student_id IS NULL AND reviewed_by IS NULL AND reviewed_at IS NULL AND rejection_reason IS NULL)
      OR (status='APPROVED' AND pending_student_id IS NULL AND approved_student_id=student_user_id AND reviewed_by IS NOT NULL AND reviewed_at IS NOT NULL AND rejection_reason IS NULL)
      OR (status='REJECTED' AND pending_student_id IS NULL AND approved_student_id IS NULL AND reviewed_by IS NOT NULL AND reviewed_at IS NOT NULL AND rejection_reason IS NOT NULL AND CHAR_LENGTH(TRIM(rejection_reason)) BETWEEN 1 AND 1000)
    )
);
CREATE INDEX idx_second_internship_requests_status ON second_internship_requests(status,requested_at);
CREATE INDEX idx_second_internship_requests_student ON second_internship_requests(student_user_id,requested_at);
