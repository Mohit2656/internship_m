-- A grant is scoped to one student, one date, and the assignment that authorized it.
CREATE TABLE late_attendance_permissions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_user_id BIGINT NOT NULL REFERENCES users (id),
    assignment_id BIGINT NOT NULL REFERENCES mentor_student_assignments (id),
    attendance_date DATE NOT NULL,
    enabled BOOLEAN NOT NULL,
    authorized_by BIGINT NOT NULL REFERENCES users (id),
    authorized_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_late_attendance_permission_student_date UNIQUE (student_user_id, attendance_date)
);

-- Prior grant/revoke events remain intact when the effective permission changes.
CREATE TABLE late_attendance_permission_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    permission_id BIGINT NOT NULL REFERENCES late_attendance_permissions (id),
    assignment_id BIGINT NOT NULL REFERENCES mentor_student_assignments (id),
    student_user_id BIGINT NOT NULL REFERENCES users (id),
    attendance_date DATE NOT NULL,
    enabled BOOLEAN NOT NULL,
    changed_by BIGINT NOT NULL REFERENCES users (id),
    changed_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_late_attendance_permission_audit_student_date
    ON late_attendance_permission_audit (student_user_id, attendance_date, changed_at);

-- Existing records retain their original data; only the new boolean receives its default.
ALTER TABLE attendance_records ADD COLUMN submitted_late BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE attendance_records ADD COLUMN late_authorized_by BIGINT REFERENCES users (id);
ALTER TABLE attendance_records ADD COLUMN late_authorized_at TIMESTAMP(6) WITH TIME ZONE;
ALTER TABLE attendance_records ADD COLUMN automatic_absent_at TIMESTAMP(6) WITH TIME ZONE;

CREATE TABLE attendance_submission_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attendance_id BIGINT NOT NULL REFERENCES attendance_records (id),
    event_type VARCHAR(30) NOT NULL,
    event_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    attendance_result VARCHAR(20) NOT NULL,
    verification_status VARCHAR(20) NOT NULL,
    verification_basis VARCHAR(20) NOT NULL,
    submission_type VARCHAR(30) NOT NULL,
    authorized_by BIGINT REFERENCES users (id),
    authorized_at TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT ck_attendance_submission_audit_event_type
        CHECK (event_type IN ('AUTO_ABSENT', 'LATE_SUBMISSION')),
    CONSTRAINT uk_attendance_submission_audit_event UNIQUE (attendance_id, event_type)
);
