-- Keep the singleton active-session pointer as the only source of ACTIVE state.
ALTER TABLE academic_sessions ADD COLUMN closed_at TIMESTAMP(6) WITH TIME ZONE;
ALTER TABLE academic_sessions ADD COLUMN closed_by BIGINT REFERENCES users(id);
ALTER TABLE academic_sessions ADD CONSTRAINT ck_academic_session_closure CHECK (
    (closed_at IS NULL AND closed_by IS NULL) OR (closed_at IS NOT NULL AND closed_by IS NOT NULL)
);

-- Intentionally no FK from session_id to academic_sessions: the immutable
-- identity/name snapshot and deletion event must survive deleting an empty session.
CREATE TABLE academic_session_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL,
    session_name VARCHAR(60) NOT NULL,
    action VARCHAR(30) NOT NULL CHECK (action IN ('CREATED','ACTIVATED','CLOSED','REOPENED','DELETED','DATES_RECORDED')),
    performed_by BIGINT REFERENCES users(id),
    performed_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_academic_session_events_session ON academic_session_events(session_id,id);
CREATE INDEX idx_completion_events_academic_session ON internship_completion_events(academic_session_id);

-- Preserve known metadata without inventing past closing dates or administrators.
INSERT INTO academic_session_events(session_id,session_name,action,performed_by,performed_at)
SELECT id,name,'CREATED',created_by,created_at FROM academic_sessions;
INSERT INTO academic_session_events(session_id,session_name,action,performed_by,performed_at)
SELECT s.id,s.name,'ACTIVATED',c.activated_by,c.activated_at
FROM academic_session_settings c JOIN academic_sessions s ON s.id=c.active_session_id
WHERE c.activated_at IS NOT NULL;
