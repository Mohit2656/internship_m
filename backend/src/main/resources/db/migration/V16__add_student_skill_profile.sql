CREATE TABLE student_skills (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    professional_profile_id BIGINT NOT NULL,
    display_name VARCHAR(100) NOT NULL,
    normalized_name VARCHAR(100) NOT NULL,
    active_normalized_name VARCHAR(100),
    source VARCHAR(30) NOT NULL,
    source_resume_analysis_id BIGINT,
    is_active BOOLEAN NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_student_skills PRIMARY KEY (id),
    CONSTRAINT fk_student_skills_profile FOREIGN KEY (professional_profile_id) REFERENCES student_professional_profiles (id) ON DELETE CASCADE,
    CONSTRAINT fk_student_skills_analysis FOREIGN KEY (source_resume_analysis_id) REFERENCES resume_analyses (id) ON DELETE SET NULL,
    CONSTRAINT uk_student_skills_active UNIQUE (professional_profile_id, active_normalized_name),
    CONSTRAINT chk_student_skills_source CHECK (source IN ('AI_EXTRACTED', 'STUDENT_ADDED')),
    CONSTRAINT chk_student_skills_active_name CHECK (
        (is_active = TRUE AND active_normalized_name = normalized_name)
        OR (is_active = FALSE AND active_normalized_name IS NULL)
    )
);

CREATE TABLE student_skill_suggestions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    professional_profile_id BIGINT NOT NULL,
    resume_analysis_id BIGINT NOT NULL,
    extracted_skill_id BIGINT NOT NULL,
    display_name VARCHAR(100) NOT NULL,
    normalized_name VARCHAR(100) NOT NULL,
    review_status VARCHAR(20) NOT NULL,
    resolved_student_skill_id BIGINT,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    reviewed_at TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT pk_student_skill_suggestions PRIMARY KEY (id),
    CONSTRAINT fk_student_skill_suggestions_profile FOREIGN KEY (professional_profile_id) REFERENCES student_professional_profiles (id) ON DELETE CASCADE,
    CONSTRAINT fk_student_skill_suggestions_analysis FOREIGN KEY (resume_analysis_id) REFERENCES resume_analyses (id) ON DELETE CASCADE,
    CONSTRAINT fk_student_skill_suggestions_extracted FOREIGN KEY (extracted_skill_id) REFERENCES resume_extracted_skills (id) ON DELETE CASCADE,
    CONSTRAINT fk_student_skill_suggestions_resolved FOREIGN KEY (resolved_student_skill_id) REFERENCES student_skills (id) ON DELETE SET NULL,
    CONSTRAINT uk_student_skill_suggestions_extracted UNIQUE (extracted_skill_id),
    CONSTRAINT chk_student_skill_suggestions_status CHECK (review_status IN ('PENDING', 'CONFIRMED', 'REJECTED'))
);

CREATE INDEX idx_student_skills_profile_active ON student_skills (professional_profile_id, is_active);
CREATE INDEX idx_student_skill_suggestions_analysis_status ON student_skill_suggestions (resume_analysis_id, review_status);
