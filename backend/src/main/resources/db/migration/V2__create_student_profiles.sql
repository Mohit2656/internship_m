CREATE TABLE student_profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id BIGINT NOT NULL,
    student_name VARCHAR(150) NOT NULL,
    branch VARCHAR(40) NOT NULL,
    uid VARCHAR(50) NOT NULL,
    roll_number VARCHAR(50) NOT NULL,
    permanent_address VARCHAR(1000) NOT NULL,
    current_address VARCHAR(1000) NULL,
    personal_email VARCHAR(254) NOT NULL,
    institute_email VARCHAR(254) NOT NULL,
    phone_number VARCHAR(25) NOT NULL,
    guardian_name VARCHAR(150) NOT NULL,
    guardian_contact VARCHAR(25) NOT NULL,
    emergency_contact VARCHAR(25) NOT NULL,
    blood_group VARCHAR(5) NOT NULL,
    aadhaar_encrypted VARCHAR(255) NOT NULL,
    aadhaar_last_four VARCHAR(4) NOT NULL,
    faculty_mentor_name VARCHAR(150) NOT NULL,
    faculty_mentor_contact VARCHAR(25) NOT NULL,
    internship_coordinator_name VARCHAR(150) NOT NULL,
    internship_coordinator_contact VARCHAR(25) NOT NULL,
    cdc_coordinator_name VARCHAR(150) NOT NULL,
    cdc_coordinator_contact VARCHAR(25) NOT NULL,
    academic_year VARCHAR(9) NOT NULL,
    semester INT NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_student_profiles PRIMARY KEY (id),
    CONSTRAINT uk_student_profiles_user UNIQUE (user_id),
    CONSTRAINT uk_student_profiles_uid UNIQUE (uid),
    CONSTRAINT uk_student_profiles_institute_email UNIQUE (institute_email),
    CONSTRAINT uk_student_profiles_roll_identity UNIQUE (branch, academic_year, roll_number),
    CONSTRAINT fk_student_profiles_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT chk_student_profiles_semester CHECK (semester BETWEEN 1 AND 8),
    CONSTRAINT chk_student_profiles_branch CHECK (branch IN ('COMPUTER_ENGINEERING','INFORMATION_TECHNOLOGY','ELECTRONICS','ELECTRICAL','MECHANICAL','CIVIL'))
);
CREATE INDEX idx_student_profiles_name ON student_profiles (student_name);
CREATE INDEX idx_student_profiles_branch ON student_profiles (branch);
CREATE INDEX idx_student_profiles_academic_year ON student_profiles (academic_year);
CREATE INDEX idx_student_profiles_semester ON student_profiles (semester);
