-- Current student academics only. Historical sessions, report submissions and
-- internship/attendance/mentor identities are deliberately not rewritten.
ALTER TABLE student_profiles ADD COLUMN IF NOT EXISTS section VARCHAR(1);
ALTER TABLE student_accounts ADD COLUMN IF NOT EXISTS section VARCHAR(1);
ALTER TABLE student_profiles ADD COLUMN IF NOT EXISTS legacy_roll_identity_conflict BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE student_profiles ADD COLUMN IF NOT EXISTS roll_identity_key VARCHAR(50);

CREATE TABLE student_academic_normalization_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_type VARCHAR(30) NOT NULL,
    entity_id BIGINT NOT NULL,
    student_user_id BIGINT NOT NULL,
    previous_branch VARCHAR(40),
    previous_semester INTEGER,
    previous_section VARCHAR(255),
    normalized_section VARCHAR(1),
    section_needs_review BOOLEAN NOT NULL,
    normalized_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_student_academic_normalization UNIQUE(entity_type, entity_id)
);

INSERT INTO student_academic_normalization_audit
    (entity_type, entity_id, student_user_id, previous_branch, previous_semester,
     previous_section, normalized_section, section_needs_review)
SELECT 'PROFILE', id, user_id, branch, semester, section,
       CASE WHEN UPPER(TRIM(section)) IN ('A','B') THEN UPPER(TRIM(section)) END,
       section IS NULL OR UPPER(TRIM(section)) NOT IN ('A','B')
FROM student_profiles;
INSERT INTO student_academic_normalization_audit
    (entity_type, entity_id, student_user_id, previous_semester,
     previous_section, normalized_section, section_needs_review)
SELECT 'ACCOUNT', id, user_id, semester, section,
       CASE WHEN UPPER(TRIM(section)) IN ('A','B') THEN UPPER(TRIM(section)) END,
       section IS NULL OR UPPER(TRIM(section)) NOT IN ('A','B')
FROM student_accounts;

-- Old branch-scoped rolls may repeat after branch normalization. Preserve all
-- original rolls and valid A/B sections; conflicts remain explicitly reviewable.
ALTER TABLE student_profiles DROP CONSTRAINT IF EXISTS uk_student_profiles_roll_identity;
ALTER TABLE student_profiles DROP CONSTRAINT IF EXISTS chk_student_profiles_branch;
ALTER TABLE student_profiles DROP CONSTRAINT IF EXISTS chk_student_profiles_semester;
ALTER TABLE student_accounts DROP CONSTRAINT IF EXISTS chk_student_accounts_semester;
UPDATE student_profiles SET branch='COMPUTER_ENGINEERING', semester=8,
    section=CASE WHEN UPPER(TRIM(section)) IN ('A','B') THEN UPPER(TRIM(section)) END;
UPDATE student_accounts SET semester=8,
    section=CASE WHEN UPPER(TRIM(section)) IN ('A','B') THEN UPPER(TRIM(section)) END;

-- Copy a recorded valid section only when the other record has no assignment.
UPDATE student_profiles p SET section=(SELECT a.section FROM student_accounts a WHERE a.user_id=p.user_id)
WHERE p.section IS NULL AND EXISTS (SELECT 1 FROM student_accounts a WHERE a.user_id=p.user_id AND a.section IN ('A','B'));
UPDATE student_accounts a SET section=(SELECT p.section FROM student_profiles p WHERE p.user_id=a.user_id)
WHERE a.section IS NULL AND EXISTS (SELECT 1 FROM student_profiles p WHERE p.user_id=a.user_id AND p.section IN ('A','B'));
UPDATE student_profiles p SET legacy_roll_identity_conflict=TRUE
WHERE p.section IS NOT NULL AND EXISTS (
    SELECT 1 FROM student_profiles other
    WHERE other.id<>p.id AND other.academic_year=p.academic_year
      AND other.section=p.section AND LOWER(TRIM(other.roll_number))=LOWER(TRIM(p.roll_number))
);
UPDATE student_profiles SET roll_identity_key=LOWER(TRIM(roll_number)) WHERE legacy_roll_identity_conflict=FALSE;

ALTER TABLE student_profiles ALTER COLUMN branch SET DEFAULT 'COMPUTER_ENGINEERING';
ALTER TABLE student_profiles ALTER COLUMN semester SET DEFAULT 8;
ALTER TABLE student_accounts ALTER COLUMN semester SET DEFAULT 8;
ALTER TABLE student_profiles ADD CONSTRAINT chk_student_profiles_branch CHECK (branch='COMPUTER_ENGINEERING');
ALTER TABLE student_profiles ADD CONSTRAINT chk_student_profiles_semester CHECK (semester=8);
ALTER TABLE student_accounts ADD CONSTRAINT chk_student_accounts_semester CHECK (semester=8);
ALTER TABLE student_profiles ADD CONSTRAINT chk_student_profiles_section CHECK (section IS NULL OR section IN ('A','B'));
ALTER TABLE student_accounts ADD CONSTRAINT chk_student_accounts_section CHECK (section IS NULL OR section IN ('A','B'));
CREATE INDEX idx_student_profiles_section ON student_profiles(section);
CREATE UNIQUE INDEX uk_student_profiles_section_roll_identity
    ON student_profiles(academic_year, section, roll_identity_key);
