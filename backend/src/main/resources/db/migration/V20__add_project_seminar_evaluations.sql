CREATE TABLE project_seminar_evaluations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    student_user_id BIGINT NOT NULL,
    mentor_user_id BIGINT NOT NULL,
    score DECIMAL(7,2) NOT NULL,
    maximum_score DECIMAL(7,2) NOT NULL,
    remarks VARCHAR(2000),
    evaluation_date DATE NOT NULL,
    finalized BOOLEAN NOT NULL DEFAULT FALSE,
    finalized_at TIMESTAMP(6) WITH TIME ZONE,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_project_seminar_evaluations PRIMARY KEY (id),
    CONSTRAINT uk_project_seminar_evaluations_student UNIQUE (student_user_id),
    CONSTRAINT fk_project_seminar_evaluations_student FOREIGN KEY (student_user_id) REFERENCES users (id),
    CONSTRAINT fk_project_seminar_evaluations_mentor FOREIGN KEY (mentor_user_id) REFERENCES users (id),
    CONSTRAINT ck_project_seminar_evaluations_scores CHECK (maximum_score > 0 AND score >= 0 AND score <= maximum_score),
    CONSTRAINT ck_project_seminar_evaluations_finalized CHECK (
        (finalized = FALSE AND finalized_at IS NULL) OR (finalized = TRUE AND finalized_at IS NOT NULL)
    )
);

CREATE INDEX idx_project_seminar_evaluations_mentor ON project_seminar_evaluations (mentor_user_id, finalized);
CREATE INDEX idx_project_seminar_evaluations_date ON project_seminar_evaluations (evaluation_date);
