-- New submissions only: historical evidence keeps its original values and no invented capture time.
ALTER TABLE attendance_evidence ADD COLUMN location_verification_status VARCHAR(40);
ALTER TABLE attendance_evidence ADD COLUMN location_captured_at TIMESTAMP(6) WITH TIME ZONE;
ALTER TABLE attendance_evidence ADD COLUMN workplace_revision BIGINT;
ALTER TABLE attendance_evidence ADD CONSTRAINT ck_attendance_location_status CHECK (
    location_verification_status IS NULL OR location_verification_status IN (
        'VERIFIED','OUTSIDE_RADIUS','INSUFFICIENT_ACCURACY','LOCATION_UNAVAILABLE',
        'WORKPLACE_NOT_APPROVED','STALE_LOCATION','NOT_APPLICABLE'));
ALTER TABLE attendance_evidence ADD CONSTRAINT ck_attendance_workplace_revision
    CHECK (workplace_revision IS NULL OR workplace_revision >= 1);

CREATE TABLE attendance_location_verification_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attendance_id BIGINT NOT NULL UNIQUE REFERENCES attendance_records(id) ON DELETE CASCADE,
    student_user_id BIGINT NOT NULL,
    verified_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    location_status VARCHAR(40) NOT NULL,
    workplace_revision BIGINT,
    latitude NUMERIC(9,6),
    longitude NUMERIC(10,6),
    gps_accuracy_meters NUMERIC(8,2),
    location_captured_at TIMESTAMP(6) WITH TIME ZONE,
    expected_latitude NUMERIC(9,6),
    expected_longitude NUMERIC(10,6),
    geofence_radius_meters NUMERIC(8,2),
    distance_meters NUMERIC(10,2),
    location_check_passed BOOLEAN
);
