CREATE TABLE mentor_notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mentor_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    student_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    attendance_id BIGINT NOT NULL REFERENCES attendance_records(id) ON DELETE CASCADE,
    notification_type VARCHAR(40) NOT NULL,
    title VARCHAR(300) NOT NULL,
    message TEXT NOT NULL,
    action_url VARCHAR(500) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    read_at TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT uk_mentor_notification_attendance UNIQUE(attendance_id)
);
CREATE INDEX idx_mentor_notifications_inbox ON mentor_notifications(mentor_user_id,created_at,id);
CREATE INDEX idx_mentor_notifications_unread ON mentor_notifications(mentor_user_id,read_at);
