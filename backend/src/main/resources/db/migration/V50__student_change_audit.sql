CREATE TABLE student_change_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    change_type VARCHAR(40) NOT NULL,
    internship_id BIGINT REFERENCES internship_details(id) ON DELETE CASCADE,
    changed_fields TEXT NOT NULL,
    before_value TEXT,
    after_value TEXT,
    occurred_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_student_change_audit_student ON student_change_audit (student_user_id, occurred_at);

