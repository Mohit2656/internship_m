CREATE TABLE opportunities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    company_name VARCHAR(200) NOT NULL,
    title VARCHAR(200) NOT NULL,
    description TEXT,
    company_website VARCHAR(500),
    location VARCHAR(200),
    internship_mode VARCHAR(20),
    duration_months INTEGER,
    stipend_amount NUMERIC(12, 2) NOT NULL,
    currency VARCHAR(3) NOT NULL,
    application_deadline DATE,
    minimum_cgpa NUMERIC(4, 2),
    status VARCHAR(20) NOT NULL,
    created_by BIGINT NOT NULL,
    published_at TIMESTAMP(6) WITH TIME ZONE,
    closed_at TIMESTAMP(6) WITH TIME ZONE,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_opportunities PRIMARY KEY (id),
    CONSTRAINT fk_opportunities_created_by FOREIGN KEY (created_by) REFERENCES users (id),
    CONSTRAINT chk_opportunities_mode CHECK (internship_mode IS NULL OR internship_mode IN ('ONSITE', 'HYBRID', 'REMOTE')),
    CONSTRAINT chk_opportunities_status CHECK (status IN ('DRAFT', 'PUBLISHED', 'CLOSED')),
    CONSTRAINT chk_opportunities_duration CHECK (duration_months IS NULL OR duration_months > 0),
    CONSTRAINT chk_opportunities_stipend CHECK (stipend_amount >= 0),
    CONSTRAINT chk_opportunities_cgpa CHECK (minimum_cgpa IS NULL OR (minimum_cgpa >= 0 AND minimum_cgpa <= 10))
);

CREATE TABLE opportunity_eligible_branches (
    opportunity_id BIGINT NOT NULL,
    branch VARCHAR(50) NOT NULL,
    CONSTRAINT pk_opportunity_eligible_branches PRIMARY KEY (opportunity_id, branch),
    CONSTRAINT fk_opportunity_branches_opportunity FOREIGN KEY (opportunity_id) REFERENCES opportunities (id) ON DELETE CASCADE
);

CREATE TABLE opportunity_eligible_semesters (
    opportunity_id BIGINT NOT NULL,
    semester INTEGER NOT NULL,
    CONSTRAINT pk_opportunity_eligible_semesters PRIMARY KEY (opportunity_id, semester),
    CONSTRAINT fk_opportunity_semesters_opportunity FOREIGN KEY (opportunity_id) REFERENCES opportunities (id) ON DELETE CASCADE,
    CONSTRAINT chk_opportunity_semester CHECK (semester BETWEEN 1 AND 8)
);

CREATE TABLE opportunity_skills (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    opportunity_id BIGINT NOT NULL,
    display_name VARCHAR(100) NOT NULL,
    normalized_name VARCHAR(100) NOT NULL,
    requirement_type VARCHAR(20) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_opportunity_skills PRIMARY KEY (id),
    CONSTRAINT fk_opportunity_skills_opportunity FOREIGN KEY (opportunity_id) REFERENCES opportunities (id) ON DELETE CASCADE,
    CONSTRAINT uk_opportunity_skills_normalized UNIQUE (opportunity_id, requirement_type, normalized_name),
    CONSTRAINT chk_opportunity_skills_type CHECK (requirement_type IN ('REQUIRED', 'PREFERRED'))
);

CREATE INDEX idx_opportunities_status ON opportunities (status);
CREATE INDEX idx_opportunities_company ON opportunities (company_name);
CREATE INDEX idx_opportunities_deadline ON opportunities (application_deadline);
CREATE INDEX idx_opportunity_branches_branch ON opportunity_eligible_branches (branch);
CREATE INDEX idx_opportunity_semesters_semester ON opportunity_eligible_semesters (semester);
CREATE INDEX idx_opportunity_skills_lookup ON opportunity_skills (requirement_type, normalized_name);
