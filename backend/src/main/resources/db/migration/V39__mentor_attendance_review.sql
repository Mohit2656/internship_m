CREATE TABLE attendance_reviews (
    attendance_id BIGINT PRIMARY KEY REFERENCES attendance_records(id),
    status VARCHAR(20) NOT NULL,
    revision INTEGER NOT NULL CHECK (revision > 0),
    reviewer_id BIGINT NOT NULL REFERENCES users(id),
    reviewer_name VARCHAR(254) NOT NULL,
    reviewed_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    reason VARCHAR(1000),
    CONSTRAINT ck_attendance_review_status CHECK (status IN ('APPROVED','REJECTED','MANUAL_REVIEW'))
);
CREATE TABLE attendance_review_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attendance_id BIGINT NOT NULL REFERENCES attendance_records(id),
    assignment_id BIGINT NOT NULL REFERENCES mentor_student_assignments(id),
    revision INTEGER NOT NULL,
    previous_status VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL,
    reviewer_id BIGINT NOT NULL REFERENCES users(id),
    reviewer_name VARCHAR(254) NOT NULL,
    reviewed_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    reason VARCHAR(1000),
    CONSTRAINT uk_attendance_review_audit_revision UNIQUE(attendance_id,revision)
);
CREATE INDEX idx_attendance_review_status ON attendance_reviews(status,reviewed_at);
