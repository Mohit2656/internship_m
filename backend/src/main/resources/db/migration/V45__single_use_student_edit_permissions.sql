CREATE TABLE student_edit_permissions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    student_user_id BIGINT NOT NULL,
    scope VARCHAR(30) NOT NULL,
    assignment_id BIGINT NOT NULL,
    granted_by BIGINT NOT NULL,
    granted_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    status VARCHAR(20) NOT NULL,
    consumed_at TIMESTAMP(6) WITH TIME ZONE,
    revoked_at TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT pk_student_edit_permissions PRIMARY KEY (id),
    CONSTRAINT uk_student_edit_permissions_scope UNIQUE (student_user_id, scope),
    CONSTRAINT fk_student_edit_permissions_student FOREIGN KEY (student_user_id) REFERENCES users (id),
    CONSTRAINT fk_student_edit_permissions_assignment FOREIGN KEY (assignment_id) REFERENCES mentor_student_assignments (id),
    CONSTRAINT fk_student_edit_permissions_grantor FOREIGN KEY (granted_by) REFERENCES users (id),
    CONSTRAINT ck_student_edit_permissions_scope CHECK (scope IN ('INTERNSHIP_DETAILS', 'STUDENT_PROFILE')),
    CONSTRAINT ck_student_edit_permissions_status CHECK (status IN ('ACTIVE', 'CONSUMED', 'REVOKED')),
    CONSTRAINT ck_student_edit_permissions_dates CHECK (expires_at > granted_at)
);

CREATE INDEX idx_student_edit_permissions_assignment ON student_edit_permissions (assignment_id);

CREATE TABLE student_edit_permission_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    permission_id BIGINT NOT NULL,
    student_user_id BIGINT NOT NULL,
    scope VARCHAR(30) NOT NULL,
    event_type VARCHAR(20) NOT NULL,
    actor_user_id BIGINT NOT NULL,
    occurred_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    before_value TEXT,
    after_value TEXT,
    CONSTRAINT pk_student_edit_permission_audit PRIMARY KEY (id),
    CONSTRAINT fk_student_edit_permission_audit_permission FOREIGN KEY (permission_id) REFERENCES student_edit_permissions (id),
    CONSTRAINT fk_student_edit_permission_audit_student FOREIGN KEY (student_user_id) REFERENCES users (id),
    CONSTRAINT fk_student_edit_permission_audit_actor FOREIGN KEY (actor_user_id) REFERENCES users (id),
    CONSTRAINT ck_student_edit_permission_audit_scope CHECK (scope IN ('INTERNSHIP_DETAILS', 'STUDENT_PROFILE')),
    CONSTRAINT ck_student_edit_permission_audit_event CHECK (event_type IN ('GRANTED', 'CONSUMED', 'REVOKED'))
);

CREATE INDEX idx_student_edit_permission_audit_student ON student_edit_permission_audit (student_user_id, occurred_at);
