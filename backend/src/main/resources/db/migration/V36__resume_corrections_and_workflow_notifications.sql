CREATE TABLE resume_corrections (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    resume_id BIGINT NOT NULL REFERENCES student_resumes(id) ON DELETE CASCADE,
    revision INTEGER NOT NULL,
    values_json TEXT NOT NULL,
    source VARCHAR(30) NOT NULL,
    editor_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    editor_name VARCHAR(254) NOT NULL,
    edited_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_resume_correction_revision UNIQUE(resume_id,revision)
);
