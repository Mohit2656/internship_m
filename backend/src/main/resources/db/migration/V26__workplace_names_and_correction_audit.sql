ALTER TABLE internship_locations ADD COLUMN workplace_name VARCHAR(255);
CREATE TABLE workplace_correction_audit (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 internship_id BIGINT NOT NULL REFERENCES internship_details(id),
 correcting_user_id BIGINT NOT NULL REFERENCES users(id),
 corrected_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
 reason VARCHAR(500) NOT NULL,
 old_latitude NUMERIC(9,6), old_longitude NUMERIC(10,6), old_place_id VARCHAR(255),
 new_latitude NUMERIC(9,6) NOT NULL, new_longitude NUMERIC(10,6) NOT NULL, new_place_id VARCHAR(255) NOT NULL,
 new_radius_meters NUMERIC(8,2) NOT NULL CHECK (new_radius_meters BETWEEN 10 AND 5000)
);
