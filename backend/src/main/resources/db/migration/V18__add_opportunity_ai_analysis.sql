CREATE TABLE opportunity_ai_analyses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    opportunity_id BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL,
    input_hash VARCHAR(64) NOT NULL,
    model_name VARCHAR(200),
    model_version VARCHAR(200),
    started_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    completed_at TIMESTAMP(6) WITH TIME ZONE,
    failure_reason_safe VARCHAR(100),
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_opportunity_ai_analyses PRIMARY KEY (id),
    CONSTRAINT fk_opportunity_ai_analysis_opportunity FOREIGN KEY (opportunity_id) REFERENCES opportunities (id) ON DELETE CASCADE,
    CONSTRAINT chk_opportunity_ai_analysis_status CHECK (status IN ('PENDING', 'ANALYZED', 'FAILED'))
);

CREATE TABLE opportunity_ai_skill_suggestions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    analysis_id BIGINT NOT NULL,
    raw_name VARCHAR(100) NOT NULL,
    display_name VARCHAR(100) NOT NULL,
    normalized_name VARCHAR(100) NOT NULL,
    suggested_requirement_type VARCHAR(20) NOT NULL,
    review_status VARCHAR(20) NOT NULL,
    confirmed_skill_id BIGINT,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_opportunity_ai_skill_suggestions PRIMARY KEY (id),
    CONSTRAINT fk_opportunity_ai_skill_analysis FOREIGN KEY (analysis_id) REFERENCES opportunity_ai_analyses (id) ON DELETE CASCADE,
    CONSTRAINT fk_opportunity_ai_confirmed_skill FOREIGN KEY (confirmed_skill_id) REFERENCES opportunity_skills (id) ON DELETE SET NULL,
    CONSTRAINT uk_opportunity_ai_skill_suggestion UNIQUE (analysis_id, suggested_requirement_type, normalized_name),
    CONSTRAINT chk_opportunity_ai_skill_type CHECK (suggested_requirement_type IN ('REQUIRED', 'PREFERRED')),
    CONSTRAINT chk_opportunity_ai_skill_review CHECK (review_status IN ('PENDING', 'CONFIRMED', 'REJECTED'))
);

CREATE TABLE opportunity_ai_signals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    analysis_id BIGINT NOT NULL,
    signal_type VARCHAR(30) NOT NULL,
    display_value VARCHAR(300) NOT NULL,
    normalized_value VARCHAR(300) NOT NULL,
    sort_order INTEGER NOT NULL,
    CONSTRAINT pk_opportunity_ai_signals PRIMARY KEY (id),
    CONSTRAINT fk_opportunity_ai_signal_analysis FOREIGN KEY (analysis_id) REFERENCES opportunity_ai_analyses (id) ON DELETE CASCADE,
    CONSTRAINT uk_opportunity_ai_signal UNIQUE (analysis_id, signal_type, normalized_value),
    CONSTRAINT chk_opportunity_ai_signal_type CHECK (signal_type IN ('ROLE', 'RESPONSIBILITY'))
);

CREATE INDEX idx_opportunity_ai_analysis_latest ON opportunity_ai_analyses (opportunity_id, created_at DESC);
CREATE INDEX idx_opportunity_ai_analysis_pending ON opportunity_ai_analyses (opportunity_id, status);
CREATE INDEX idx_opportunity_ai_skill_review ON opportunity_ai_skill_suggestions (analysis_id, review_status);
