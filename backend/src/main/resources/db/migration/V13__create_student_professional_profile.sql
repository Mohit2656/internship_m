CREATE TABLE student_professional_profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    student_user_id BIGINT NOT NULL,
    headline VARCHAR(160),
    career_interests VARCHAR(1000),
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_student_professional_profiles PRIMARY KEY (id),
    CONSTRAINT uk_student_professional_profiles_student UNIQUE (student_user_id),
    CONSTRAINT fk_student_professional_profiles_student FOREIGN KEY (student_user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE TABLE student_resumes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    professional_profile_id BIGINT NOT NULL,
    original_filename VARCHAR(255) NOT NULL,
    storage_key VARCHAR(255) NOT NULL,
    content_type VARCHAR(100) NOT NULL,
    file_size BIGINT NOT NULL,
    uploaded_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    parsing_status VARCHAR(20) NOT NULL DEFAULT 'NOT_PARSED',
    CONSTRAINT pk_student_resumes PRIMARY KEY (id),
    CONSTRAINT uk_student_resumes_profile UNIQUE (professional_profile_id),
    CONSTRAINT uk_student_resumes_storage_key UNIQUE (storage_key),
    CONSTRAINT fk_student_resumes_profile FOREIGN KEY (professional_profile_id) REFERENCES student_professional_profiles (id) ON DELETE CASCADE,
    CONSTRAINT chk_student_resumes_file_size CHECK (file_size > 0),
    CONSTRAINT chk_student_resumes_active CHECK (is_active = TRUE),
    CONSTRAINT chk_student_resumes_parsing_status CHECK (parsing_status IN ('NOT_PARSED', 'PENDING', 'PARSED', 'FAILED'))
);

CREATE INDEX idx_student_resumes_uploaded_at ON student_resumes (uploaded_at);
