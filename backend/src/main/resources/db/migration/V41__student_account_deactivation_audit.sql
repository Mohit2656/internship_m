-- Student deletion retains the account and every dependent historical row/file.
CREATE TABLE student_account_deactivation_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_user_id BIGINT NOT NULL UNIQUE REFERENCES users(id),
    initiated_by BIGINT NOT NULL REFERENCES users(id),
    deactivated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    reason VARCHAR(500) NOT NULL CHECK (CHAR_LENGTH(TRIM(reason)) BETWEEN 5 AND 500),
    dependency_summary TEXT NOT NULL
);
CREATE INDEX idx_student_deactivation_actor ON student_account_deactivation_audit(initiated_by,deactivated_at);
