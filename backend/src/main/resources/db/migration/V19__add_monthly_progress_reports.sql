CREATE TABLE monthly_progress_reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    student_internship_id BIGINT NOT NULL,
    report_month_number INT NOT NULL,
    period_start DATE NOT NULL,
    period_end DATE NOT NULL,
    work_description VARCHAR(3000) NOT NULL,
    photo_storage_key VARCHAR(80) NOT NULL,
    photo_original_name VARCHAR(255) NOT NULL,
    photo_mime_type VARCHAR(50) NOT NULL,
    photo_size BIGINT NOT NULL,
    exif_captured_at TIMESTAMP(6) WITH TIME ZONE,
    exif_latitude DECIMAL(9,6),
    exif_longitude DECIMAL(10,6),
    location_name VARCHAR(255),
    submitted_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_monthly_progress_reports PRIMARY KEY (id),
    CONSTRAINT fk_monthly_progress_reports_internship FOREIGN KEY (student_internship_id) REFERENCES internship_details (id) ON DELETE CASCADE,
    CONSTRAINT uk_monthly_progress_reports_month UNIQUE (student_internship_id, report_month_number),
    CONSTRAINT ck_monthly_progress_reports_month CHECK (report_month_number > 0),
    CONSTRAINT ck_monthly_progress_reports_period CHECK (period_end >= period_start),
    CONSTRAINT ck_monthly_progress_reports_description CHECK (CHAR_LENGTH(TRIM(work_description)) BETWEEN 1 AND 3000),
    CONSTRAINT ck_monthly_progress_reports_photo CHECK (photo_size > 0 AND photo_mime_type IN ('image/jpeg', 'image/png')),
    CONSTRAINT ck_monthly_progress_reports_latitude CHECK (exif_latitude IS NULL OR exif_latitude BETWEEN -90 AND 90),
    CONSTRAINT ck_monthly_progress_reports_longitude CHECK (exif_longitude IS NULL OR exif_longitude BETWEEN -180 AND 180)
);

CREATE INDEX idx_monthly_progress_reports_internship ON monthly_progress_reports (student_internship_id);
CREATE INDEX idx_monthly_progress_reports_submitted_at ON monthly_progress_reports (submitted_at DESC);
