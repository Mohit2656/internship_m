-- Weekly records supplement the existing monthly reports. Superseded empty periods
-- remain archived; submitted period boundaries are protected by the service.
CREATE TABLE weekly_internship_periods (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    internship_id BIGINT NOT NULL REFERENCES internship_details(id) ON DELETE CASCADE,
    week_number INTEGER NOT NULL CHECK (week_number > 0),
    period_start DATE NOT NULL,
    period_end DATE NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_weekly_period_dates CHECK (period_end >= period_start AND period_end <= period_start + 6),
    CONSTRAINT uk_weekly_period_bounds UNIQUE (internship_id,week_number,period_start,period_end)
);
CREATE INDEX idx_weekly_period_internship ON weekly_internship_periods(internship_id,active,week_number);
CREATE TABLE weekly_progress_reports (
    period_id BIGINT PRIMARY KEY REFERENCES weekly_internship_periods(id) ON DELETE CASCADE,
    work_description VARCHAR(3000) NOT NULL,
    revision INTEGER NOT NULL CHECK (revision > 0),
    review_status VARCHAR(30) NOT NULL,
    submitted_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    reviewer_id BIGINT REFERENCES users(id),
    reviewed_at TIMESTAMP(6) WITH TIME ZONE,
    rejection_reason VARCHAR(1000),
    CONSTRAINT ck_weekly_review_state CHECK (
        (review_status='PENDING_MENTOR_REVIEW' AND reviewer_id IS NULL AND reviewed_at IS NULL AND rejection_reason IS NULL)
        OR (review_status='APPROVED' AND reviewer_id IS NOT NULL AND reviewed_at IS NOT NULL AND rejection_reason IS NULL)
        OR (review_status='REJECTED' AND reviewer_id IS NOT NULL AND reviewed_at IS NOT NULL AND rejection_reason IS NOT NULL AND CHAR_LENGTH(TRIM(rejection_reason)) BETWEEN 1 AND 1000)
    )
);
CREATE TABLE weekly_progress_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    period_id BIGINT NOT NULL REFERENCES weekly_progress_reports(period_id) ON DELETE CASCADE,
    revision INTEGER NOT NULL CHECK (revision > 0),
    event_type VARCHAR(30) NOT NULL CHECK (event_type IN ('SUBMITTED','APPROVED','REJECTED')),
    actor_id BIGINT NOT NULL REFERENCES users(id),
    performed_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    work_description VARCHAR(3000) NOT NULL,
    reason VARCHAR(1000),
    CONSTRAINT uk_weekly_revision_event UNIQUE (period_id,revision,event_type),
    CONSTRAINT ck_weekly_event_reason CHECK (event_type <> 'REJECTED' OR (reason IS NOT NULL AND CHAR_LENGTH(TRIM(reason)) BETWEEN 1 AND 1000))
);
CREATE INDEX idx_weekly_event_history ON weekly_progress_events(period_id,id);
