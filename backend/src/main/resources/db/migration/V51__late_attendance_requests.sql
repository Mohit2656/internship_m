-- Each attempt is retained. Only an explicitly permitted rejection frees the date for resubmission.
CREATE TABLE late_attendance_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_user_id BIGINT NOT NULL REFERENCES users(id),
    internship_id BIGINT NOT NULL REFERENCES internship_details(id),
    attendance_date DATE NOT NULL,
    reason VARCHAR(1000) NOT NULL CHECK (CHAR_LENGTH(TRIM(reason)) BETWEEN 5 AND 1000),
    supporting_details VARCHAR(4000),
    requested_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING','APPROVED','REJECTED')),
    reviewer_id BIGINT REFERENCES users(id),
    reviewed_at TIMESTAMP(6) WITH TIME ZONE,
    rejection_reason VARCHAR(1000),
    resubmission_allowed BOOLEAN NOT NULL DEFAULT FALSE,
    attendance_id BIGINT REFERENCES attendance_records(id),
    active_slot INTEGER DEFAULT 1,
    CONSTRAINT uk_late_attendance_request_date UNIQUE(student_user_id, internship_id, attendance_date, active_slot),
    CONSTRAINT ck_late_attendance_request_decision CHECK (
        (status='PENDING' AND reviewer_id IS NULL AND reviewed_at IS NULL AND attendance_id IS NULL AND rejection_reason IS NULL AND resubmission_allowed=FALSE)
        OR (status='APPROVED' AND reviewer_id IS NOT NULL AND reviewed_at IS NOT NULL AND attendance_id IS NOT NULL AND rejection_reason IS NULL AND resubmission_allowed=FALSE)
        OR (status='REJECTED' AND reviewer_id IS NOT NULL AND reviewed_at IS NOT NULL AND attendance_id IS NULL)
    ),
    CONSTRAINT ck_late_attendance_request_slot CHECK (
        (status='REJECTED' AND resubmission_allowed=TRUE AND active_slot IS NULL)
        OR (resubmission_allowed=FALSE AND active_slot IS NOT NULL AND active_slot=1)
    )
);
CREATE INDEX idx_late_attendance_request_queue ON late_attendance_requests(status, requested_at, id);
CREATE INDEX idx_late_attendance_request_student ON late_attendance_requests(student_user_id, internship_id, requested_at);

-- Keep manual approvals distinct from student-captured location and liveness evidence.
ALTER TABLE attendance_records DROP CONSTRAINT ck_attendance_records_submission_type;
ALTER TABLE attendance_records ADD CONSTRAINT ck_attendance_records_submission_type
    CHECK (submission_type IN ('BASIC','PHYSICAL_CAPTURE','REMOTE_CAPTURE','AUTO_ABSENT','LATE_REQUEST'));
ALTER TABLE attendance_records DROP CONSTRAINT ck_attendance_verification_basis;
ALTER TABLE attendance_records ADD CONSTRAINT ck_attendance_verification_basis
    CHECK (verification_basis IN ('LEGACY','LIVENESS','AUTOMATIC','MANUAL'));
