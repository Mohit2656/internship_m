CREATE TABLE student_notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    event_key VARCHAR(200) NOT NULL,
    notification_type VARCHAR(40) NOT NULL,
    title VARCHAR(300) NOT NULL,
    message TEXT NOT NULL,
    rejection_reason VARCHAR(1000),
    mentor_name VARCHAR(254),
    action_url VARCHAR(500) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    read_at TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT uk_student_notification_event UNIQUE(student_user_id,event_key)
);
CREATE INDEX idx_student_notifications_inbox ON student_notifications(student_user_id,created_at,id);
CREATE INDEX idx_student_notifications_unread ON student_notifications(student_user_id,read_at);
