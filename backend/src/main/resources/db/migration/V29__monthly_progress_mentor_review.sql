-- Preserve original reports and evidence; no historical upload implies mentor approval.
ALTER TABLE monthly_progress_reports ADD COLUMN review_status VARCHAR(30) NOT NULL DEFAULT 'PENDING_MENTOR_REVIEW';
ALTER TABLE monthly_progress_reports ADD COLUMN revision INTEGER NOT NULL DEFAULT 1;
ALTER TABLE monthly_progress_reports ADD COLUMN row_version BIGINT NOT NULL DEFAULT 0;
ALTER TABLE monthly_progress_reports ADD COLUMN reviewer_id BIGINT REFERENCES users(id);
ALTER TABLE monthly_progress_reports ADD COLUMN reviewed_at TIMESTAMP(6) WITH TIME ZONE;
ALTER TABLE monthly_progress_reports ADD COLUMN rejection_reason VARCHAR(1000);
ALTER TABLE monthly_progress_reports ADD CONSTRAINT ck_monthly_review_revision CHECK (revision > 0);
ALTER TABLE monthly_progress_reports ADD CONSTRAINT ck_monthly_review_state CHECK (
 (review_status='PENDING_MENTOR_REVIEW' AND reviewer_id IS NULL AND reviewed_at IS NULL AND rejection_reason IS NULL)
 OR (review_status='APPROVED' AND reviewer_id IS NOT NULL AND reviewed_at IS NOT NULL AND rejection_reason IS NULL)
 OR (review_status='REJECTED' AND reviewer_id IS NOT NULL AND reviewed_at IS NOT NULL AND rejection_reason IS NOT NULL AND CHAR_LENGTH(TRIM(rejection_reason)) BETWEEN 1 AND 1000)
);
CREATE TABLE monthly_progress_review_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 report_id BIGINT NOT NULL REFERENCES monthly_progress_reports(id),
 revision INTEGER NOT NULL CHECK (revision > 0),
 event_type VARCHAR(30) NOT NULL CHECK (event_type IN ('SUBMITTED','APPROVED','REJECTED')),
 actor_id BIGINT NOT NULL REFERENCES users(id),
 performed_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
 reason VARCHAR(1000),
 work_description VARCHAR(3000),
 photo_storage_key VARCHAR(80),
 photo_original_name VARCHAR(255),
 image_sha256 VARCHAR(64),
 legacy_submission BOOLEAN NOT NULL DEFAULT FALSE,
 CONSTRAINT ck_monthly_event_reason CHECK (event_type <> 'REJECTED' OR (reason IS NOT NULL AND CHAR_LENGTH(TRIM(reason)) BETWEEN 1 AND 1000))
);
CREATE INDEX idx_monthly_review_events_report ON monthly_progress_review_events(report_id,revision,id);
CREATE UNIQUE INDEX uk_monthly_review_submission ON monthly_progress_review_events(report_id,revision,event_type);
INSERT INTO monthly_progress_review_events(report_id,revision,event_type,actor_id,performed_at,work_description,photo_storage_key,photo_original_name,image_sha256,legacy_submission)
SELECT r.id,1,'SUBMITTED',o.student_user_id,r.submitted_at,r.work_description,r.photo_storage_key,r.photo_original_name,r.image_sha256,TRUE
FROM monthly_progress_reports r JOIN internship_details i ON i.id=r.student_internship_id JOIN internship_onboarding o ON o.id=i.onboarding_id;
