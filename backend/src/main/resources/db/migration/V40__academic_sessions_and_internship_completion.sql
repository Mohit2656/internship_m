CREATE TABLE academic_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(60) NOT NULL UNIQUE,
    start_date DATE,
    end_date DATE,
    description VARCHAR(1000),
    created_by BIGINT REFERENCES users(id),
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK ((start_date IS NULL AND end_date IS NULL) OR (start_date IS NOT NULL AND end_date IS NOT NULL AND end_date > start_date))
);
-- One database pointer and lock serializes activation with account creation, even
-- when no session has been activated. Historical sessions are never removed.
CREATE TABLE academic_session_settings (
    id INTEGER PRIMARY KEY CHECK (id = 1),
    active_session_id BIGINT REFERENCES academic_sessions(id),
    activated_by BIGINT REFERENCES users(id),
    activated_at TIMESTAMP(6) WITH TIME ZONE
);
