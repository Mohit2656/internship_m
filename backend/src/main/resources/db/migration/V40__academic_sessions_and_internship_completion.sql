CREATE TABLE internship_completion_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    internship_id BIGINT NOT NULL REFERENCES internship_details(id),
    student_user_id BIGINT NOT NULL REFERENCES users(id),
    academic_session_id BIGINT REFERENCES academic_sessions(id),
    revision INTEGER NOT NULL CHECK (revision > 0),
    previous_status VARCHAR(30) NOT NULL,
    final_status VARCHAR(30) NOT NULL CHECK (final_status IN ('COMPLETED','IN_PROGRESS')),
    reviewer_id BIGINT NOT NULL REFERENCES users(id),
    performed_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    remarks VARCHAR(1000),
    UNIQUE(internship_id,revision),
    CHECK(final_status <> 'IN_PROGRESS' OR (remarks IS NOT NULL AND CHAR_LENGTH(TRIM(remarks)) BETWEEN 5 AND 1000))
);
