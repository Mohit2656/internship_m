package edu.institution.ims.dashboard.report;

import edu.institution.ims.security.UserPrincipal;
import org.springframework.security.access.prepost.PreAuthorize;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.*;
import java.io.IOException;
import java.nio.file.*;
import java.time.*;
import java.time.format.DateTimeFormatter;
import java.util.*;
import java.util.stream.Collectors;

@Service
@PreAuthorize("hasAnyRole('ADMIN', 'MENTOR')")
public class DashboardReportService {
    private final DashboardReportCatalog catalog;
    private final DashboardReportRepository repository;
    private final Clock clock;
    public DashboardReportService(DashboardReportCatalog catalog, DashboardReportRepository repository, Clock clock) {
        this.catalog = catalog; this.repository = repository; this.clock = clock;
    }
    public record Options(List<DashboardReportCatalog.Field> fields, List<DashboardReportCatalog.Filter> filters, String attendanceDate, String timezone, String scope) {}
    public record Preview(long studentCount, List<Map<String, Object>> students, String attendanceDate) {}
    public record Download(Path path, String filename, String contentType, int studentCount) {}
    public Options options(UserPrincipal user) {
        return new Options(catalog.fields(user), catalog.filters(user), LocalDate.now(clock).toString(), clock.getZone().getId(),
                catalog.isAdmin(user) ? "All institutional student accounts" : "Only your currently assigned students; attendance is limited to today");
    }
    @Transactional(readOnly = true, isolation = Isolation.REPEATABLE_READ)
    public Preview preview(UserPrincipal user, DashboardReportRequest request) {
        catalog.selected(user, request.fields()); var scope = repository.scope(user, request.filters());
        List<DashboardReportCatalog.Field> identity = catalog.selected(user, List.of("studentId", "studentName", "uid", "loginEmail"));
        var students = repository.page(scope, identity, 0, 20); students.forEach(row -> row.remove("_id"));
        return new Preview(repository.count(scope), students, scope.attendanceDate().toString());
    }
    @Transactional(readOnly = true, isolation = Isolation.REPEATABLE_READ)
    public Download export(UserPrincipal user, DashboardReportRequest request) throws IOException {
        var fields = catalog.selected(user, request.fields()); var scope = repository.scope(user, request.filters());
        if (request.format() == null) throw new IllegalArgumentException("Choose XLSX, CSV or PDF");
        String extension = request.format().extension();
        Path file = Files.createTempFile("ims-dashboard-report-", "." + extension);
        try {
            int total;
            try (DashboardReportWriter writer = new DashboardReportWriter(file, request.format(), fields, clock.getZone())) {
                long afterId = 0;
                while (true) {
                    var rows = repository.page(scope, fields, afterId, 250);
                    if (rows.isEmpty()) break;
                    repository.related(scope, fields, rows);
                    for (var row : rows) writer.row(row);
                    afterId = ((Number) rows.get(rows.size() - 1).get("_id")).longValue();
                }
                total = writer.count(); Map<String, String> metadata = new LinkedHashMap<>();
                metadata.put("Generated at", ZonedDateTime.now(clock).format(DateTimeFormatter.ofPattern("yyyy-MM-dd HH:mm:ss XXX")) + " (" + clock.getZone() + ")");
                metadata.put("Generated by", user.email()); metadata.put("Role", catalog.isAdmin(user) ? "III Cell Incharge (ADMIN)" : "Faculty Mentor (MENTOR)");
                metadata.put("Access scope", options(user).scope()); metadata.put("Students included", Integer.toString(total));
                metadata.put("Attendance reference date", scope.attendanceDate().toString());
                metadata.put("Applied filters", scope.filters().isEmpty() ? "None" : scope.filters().entrySet().stream().map(e -> e.getKey() + " = " + e.getValue()).collect(Collectors.joining("; ")));
                metadata.put("Selected categories", fields.stream().map(DashboardReportCatalog.Field::category).distinct().collect(Collectors.joining(", ")));
                metadata.put("Selected columns (in order)", fields.stream().map(DashboardReportCatalog.Field::label).collect(Collectors.joining(", ")));
                metadata.put("Reading this report", "One student per row in Excel and CSV. PDF uses a table for narrow selections and field/value sections for wide selections. Related records use separate lines within each value. Empty values mean unavailable data. No attendance submission is not an absent record. History filters limit related records, not student membership. AI extraction is not confirmed skill evidence. Timestamps use " + clock.getZone() + ". CSV contains only the selected headers and data rows; Excel and PDF include metadata.");
                writer.finish(metadata);
            }
            String filename = "dashboard-students-" + LocalDate.now(clock) + "." + extension;
            return new Download(file, filename, request.format().contentType(), total);
        } catch (IOException | RuntimeException error) { Files.deleteIfExists(file); throw error; }
    }
}
